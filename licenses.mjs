'use strict';

// Builds THIRD_PARTY_LICENSES from the headers of the converted transitions.

const UPSTREAM = 'https://github.com/gl-transitions/gl-transitions';
const BSD_END = 'SUCH DAMAGE.';

// The copyright and the conditions of a BSD license, written in the comments of a shader
// (as a block, or as lines starting with `//`).
export const extractLicenseNotice = (source) => {
  const text = source
    .split('\n')
    .map((line) =>
      line
        .replace(/^\s*\/\/ ?/, '')
        .replace(/^\s*\/\*+\s?/, '')
        .replace(/\s*\*\/\s*$/, '')
    )
    .join('\n');

  const end = text.indexOf(BSD_END);
  const redistribution = text.indexOf('Redistribution');
  const start = text.lastIndexOf('Copyright', redistribution);

  if (end < 0 || redistribution < 0 || start < 0) return null;

  return text
    .slice(text.lastIndexOf('\n', start) + 1, end + BSD_END.length)
    .trim();
};

// `entries`: [{ file, author, license, notice }], `upstreamLicense`: the text of the gl-transitions LICENSE.
export const buildThirdPartyLicenses = (entries, upstreamLicense) => {
  const byLicense = new Map();
  for (const entry of entries) {
    if (!byLicense.has(entry.license)) byLicense.set(entry.license, []);
    byLicense.get(entry.license).push(entry);
  }

  // MIT first, then the others by name.
  const licenses = [...byLicense.keys()].sort(
    (a, b) => (a === 'MIT' ? -1 : b === 'MIT' ? 1 : a.localeCompare(b))
  );

  const sections = licenses.map((license) => {
    const list = byLicense.get(license).sort((a, b) => a.file.localeCompare(b.file));
    const lines = list.map((e) => `- ${e.file}: ${e.author}`);

    // A license other than MIT has its own text and copyright: keep it.
    const notices = list
      .filter((e) => e.notice)
      .map((e) => `### ${e.file}\n\n${e.notice}`);
    const missing = list.filter((e) => !e.notice && license !== 'MIT');

    return [
      `## ${license} (${list.length})`,
      lines.join('\n'),
      ...(missing.length > 0
        ? [`The notice of ${missing.map((e) => e.file).join(', ')} is in the header of the shader.`]
        : []),
      ...notices,
    ].join('\n\n');
  });

  return `${[
    '# Third party licenses',
    `The shaders of the \`converted\` folder are converted from [gl-transitions](${UPSTREAM}) and keep the license of the original transition, given in the \`CREDIT\` of each file (\`Author - License\`). This file is generated by \`npm run convert\`.`,
    `## gl-transitions\n\n${upstreamLicense.trim()}`,
    sections.join('\n\n'),
  ].join('\n\n')}\n`;
};
