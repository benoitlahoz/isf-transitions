'use strict';

// Builds the JavaScript modules of the package from the converted transitions:
// `transitions.mjs` (the source of each transition, named like its gl-transitions identifier)
// and `catalog.mjs` (what describes them), with their types.

const HEADER = '// Generated by `npm run convert`: do not edit.\n';

// `entries`: [{ name, title, file, author, license, description, content }], `name` being the PascalCase identifier.
export const buildModules = (entries) => {
  const sorted = [...entries].sort((a, b) => a.name.localeCompare(b.name));

  const transitions = `${HEADER}${sorted
    .map(
      ({ name, file, content }) =>
        `/** The ISF shader \`${file}\`. */\nexport const ${name} = ${JSON.stringify(content)};\n`
    )
    .join('\n')}`;

  const transitionsTypes = `${HEADER}${sorted
    .map(({ name, file }) => `/** The ISF shader \`${file}\`. */\nexport declare const ${name}: string;\n`)
    .join('\n')}`;

  const catalog = `${HEADER}export const catalog = ${JSON.stringify(
    sorted.map(({ name, title, file, author, license, description }) => ({
      name,
      title,
      file,
      author,
      license,
      description,
    })),
    null,
    2
  )};

// The sources are loaded when asked for: the catalog stays light.
export const loadTransition = async (name) => {
  const transitions = await import('./transitions.mjs');
  if (!Object.hasOwn(transitions, name)) {
    throw new Error(\`Unknown transition '\${name}'.\`);
  }
  return transitions[name];
};
`;

  const catalogTypes = `${HEADER}/** The identifier of a transition, the name of its export in \`isf-transitions\`. */
export type TransitionName =
${sorted.map(({ name }) => `  | '${name}'`).join('\n')};

export interface TransitionInfo {
  name: TransitionName;
  /** The name to show: \`Color Phase\` for \`ColorPhase\`. */
  title: string;
  /** The file in the \`converted\` folder. */
  file: string;
  author: string;
  license: string;
  description: string;
}

export declare const catalog: readonly TransitionInfo[];

/** The ISF shader of a transition. Rejects for a name that is not in the catalog. */
export declare const loadTransition: (name: TransitionName) => Promise<string>;
`;

  return { transitions, transitionsTypes, catalog, catalogTypes };
};
